const DICTS = { vi, en };
let current = "vi";

export function setLang(lang) {
  if (LANGS.some((l) => l.code === lang)) current = lang;
}
export function getLang() {
  return current;
}
export function t(key, params) {
  const table = DICTS[current] || vi;
  let s = table[key] ?? vi[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ""));
  return s;
}

/** Lấy chuỗi theo ngôn ngữ chỉ định (dùng cho phụ đề vietsub). */
export function tIn(lang, key, params) {
  const table = DICTS[lang] || vi;
  let s = table[key] ?? vi[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ""));
  return s;
}
/** Ngôn ngữ: mặc định vi — chỉ đổi khi CRIZON_LANG được đặt rõ ràng. */
export function detectLang(env = process.env) {
  const raw = String(env.CRIZON_LANG || "").trim();
  if (/^en/i.test(raw)) return "en";
  return "vi";
}
